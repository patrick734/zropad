// Regenerates src/lib/abi.ts from the compiled contracts: node scripts/abis.mjs (after forge build).
import { readFileSync, writeFileSync } from "node:fs";
const out = (name) => JSON.parse(readFileSync(new URL(`../../contracts/out/${name}.sol/${name}.json`, import.meta.url))).abi;
const names = { hubAbi: "Zropad", marketAbi: "ZropadMarket", coinAbi: "ZropadToken", stakingAbi: "ZropadStaking", zrpdAbi: "ZRPD" };
let ts = "// Generated by scripts/abis.mjs from contracts/out. Do not edit.\n\n";
for (const [k, v] of Object.entries(names)) ts += `export const ${k} = ${JSON.stringify(out(v))} as const;\n\n`;
writeFileSync(new URL("../src/lib/abi.ts", import.meta.url), ts);
console.log("wrote src/lib/abi.ts");
